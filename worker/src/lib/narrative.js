// تولید متن مشاوره‌ای و دوستانه برای نتیجه‌ی تست‌ها و «مسیر من».
// بدون هوش مصنوعی: متن از داده‌های خود سایت (توضیح دسته‌ها، نمره‌ها، پیشنهادها) ساخته می‌شود،
// و اگر مدیر برای یک دسته «متن مشاوره‌ای» (advice_text) نوشته باشد، همان جایگزین توضیح عمومی می‌شود.
// خروجی: آرایه‌ای از پاراگراف‌ها [{ kind, text }] تا فرانت‌اند هرکدام را جدا و زیبا نشان بدهد.

const HOL = { R: 'عملی و دست‌ورز', I: 'پژوهشی و تحلیلی', A: 'هنری و خلاق', S: 'اجتماعی و کمک‌رسان', E: 'کارآفرین و رهبر', C: 'منظم و سازمانی' };
const list = (arr) => (arr.length <= 1 ? arr.join('') : arr.length === 2 ? arr.join(' و ') : arr.slice(0, -1).join('، ') + ' و ' + arr[arr.length - 1]);
const names = (xs, n) => xs.slice(0, n).map(x => x.name);
const band = (pct) => (pct >= 70 ? 'high' : pct >= 45 ? 'mid' : 'low');
const clean = (s) => String(s || '').replace(/\s+/g, ' ').trim();
const endDot = (s) => { s = clean(s); return s && !/[.!؟?…]$/.test(s) ? s + '.' : s; };

// نتیجه‌ی یک تست
export function testNarrative({ test, categories, top_codes, suggested, next_action }) {
  const P = []; const push = (kind, text) => { if (clean(text)) P.push({ kind, text: clean(text) }); };
  const ability = test.kind === 'ability';
  const cats = categories || []; const top = cats[0];
  if (!top) return [{ kind: 'intro', text: 'برای این تست هنوز نتیجه‌ی قابل‌تفسیری ثبت نشده است.' }];
  const spread = top.pct - (cats[cats.length - 1]?.pct ?? 0);
  const topSet = cats.filter(c => (top_codes || []).includes(c.code));
  const second = topSet.find(c => c.code !== top.code);
  const close = second && top.pct - second.pct <= 8;

  // ۱) آغاز
  if (top.pct < 35 && !ability) push('intro', 'ممنون که با دقت جواب دادی 🌱 نتیجه‌ات نشان می‌دهد هنوز گرایش خیلی پررنگی به یک سمت مشخص نداری. این اصلاً بد نیست؛ یعنی در مرحله‌ی کشف هستی و فرصت داری چیزهای بیشتری را امتحان کنی.');
  else if (spread < 10) push('intro', ability ? 'ممنون که تا آخر ماندی 👏 عملکردت در بخش‌های مختلف تقریباً هم‌سطح بود؛ یعنی توانایی‌هایت متعادل است و هیچ بخشی به‌شدت عقب‌تر از بقیه نیست.' : 'ممنون که با دقت جواب دادی 🌱 تصویری که از پاسخ‌هایت درآمد نسبتاً متعادل است؛ یعنی چند حوزه را تقریباً به یک اندازه دوست داری و این برایت انتخاب‌های بازتری باز می‌کند.');
  else push('intro', ability ? 'خسته نباشی! 👏 بیا با هم ببینیم عملکردت چه چیزهایی درباره‌ات می‌گوید. فراموش نکن اینجا قرار نیست نمره‌ای از «قبولی یا مردودی» بگیری؛ فقط می‌خواهیم نقاط قوتت را پیدا کنیم و جاهایی را که با کمی تمرین بهتر می‌شود.' : 'ممنون که با دقت جواب دادی 🌱 بیا ببینیم پاسخ‌هایت چه تصویری از تو ساخته‌اند. این نتیجه یک نقطه‌ی شروع برای فکر کردن است، نه یک حکم.');

  // ۲) برجسته‌ترین مورد
  const topBody = endDot(top.advice_text || top.description);
  push('top', `${ability ? 'قوی‌ترین بخش تو' : 'پررنگ‌ترین مورد در پاسخ‌هایت'} «${top.title}» بود. ${topBody}${band(top.pct) === 'high' ? (ability ? ' عملکردت اینجا واقعاً خوب بود و می‌توانی به آن تکیه کنی.' : ' همسویی‌ات با این مورد بالاست و کاملاً دیده می‌شود.') : ''}`);

  // ۳) مورد(های) نزدیک
  const others = topSet.filter(c => c.code !== top.code);
  if (others.length) {
    const t2 = others.map(c => `«${c.title}»`);
    push('others', close
      ? `جالب است که ${list(t2)} هم تقریباً هم‌وزنِ مورد اول بود. یعنی ترکیب این‌ها تصویر کامل‌تری از توست، و بهتر است مسیرهایی را در نظر بگیری که چند تا از این ویژگی‌ها را با هم داشته باشند.`
      : `در کنار آن، ${list(t2)} هم در پاسخ‌هایت دیده شد. این‌ها نقش دوم را بازی می‌کنند و می‌توانند به انتخاب‌هایت رنگ و جهت بدهند.${others[0]?.description ? ' ' + endDot(others[0].advice_text || others[0].description) : ''}`);
  }

  // ۴) بخش‌های کم‌رنگ‌تر (با لحن همدلانه)
  const lows = cats.filter(c => !topSet.find(t => t.code === c.code) && c.pct < 45).slice(-2).reverse();
  if (lows.length && spread >= 15) {
    const t3 = lows.map(c => `«${c.title}»`);
    push('growth', ability
      ? `در ${list(t3)} هنوز جای رشد داری. این به معنی «نمی‌توانی» نیست؛ این توانایی‌ها با تمرین منظم بهتر می‌شوند و لازم نیست همه را با هم درست کنی. یکی را انتخاب کن و کم‌کم جلو برو.`
      : `${list(t3)} کمتر در پاسخ‌هایت پررنگ بود. معنایش این نیست که باید از آن‌ها دور بمانی؛ فقط الان کمتر جذبت می‌کنند. اگر شغل یا رشته‌ی مورد علاقه‌ات به آن‌ها نیاز داشت، می‌توانی بعداً آرام‌آرام تمرینشان کنی.`);
  }

  // ۵) پیشنهادها به شکل جمله
  const sug = suggested || {}; const bits = [];
  if (sug.majors?.length) bits.push(`از نظر رشته، مواردی مثل ${list(names(sug.majors, 4))} برای بررسی بیشتر خوب‌اند`);
  if (sug.jobs?.length) bits.push(`در دنیای کار، شغل‌هایی مثل ${list(names(sug.jobs, 4))} با این ویژگی‌ها هماهنگ‌اند`);
  if (sug.skills?.length) bits.push(`و اگر دوست داری از همین حالا شروع کنی، یادگیری ${list(names(sug.skills, 3))} قدم عملی و کم‌هزینه‌ای است`);
  if (bits.length) push('suggest', `اگر بخواهیم این نتیجه را به انتخاب‌های واقعی نزدیک کنیم: ${bits.join('؛ ')}. این‌ها «پیشنهاد برای بررسی»اند، نه دستور؛ کافی است صفحه‌شان را بخوانی و ببینی کدام حس خوبی می‌دهد.`);

  // ۶) قدم بعدی و نکته‌ی پایانی
  if (next_action) push('next', `قدم بعدی که پیشنهاد می‌کنم: ${endDot(next_action)}`);
  if (test.result_note) push('closing', endDot(test.result_note));
  return P;
}

// نتیجه‌ی کلی «مسیر من»
export function pathNarrative({ holland, goal, chosenMajor, chosenJob, majors, jobs, abilities, planStarted, coaching, grade, testsDone }) {
  const P = []; const push = (kind, text) => { if (clean(text)) P.push({ kind, text: clean(text) }); };
  if (!holland?.length) {
    push('intro', 'سلام! 👋 مسیر تو هنوز از اول شروع نشده، و این کاملاً طبیعی است. بهترین نقطه‌ی شروع، تست علاقه است؛ حدود ۱۰ دقیقه وقت می‌گیرد و بعد از آن می‌توانم رشته‌ها و شغل‌هایی را نشانت بدهم که به شخصیت و علاقه‌ات نزدیک‌ترند.');
    if (goal?.title) push('goal', `خوشحالم که برای خودت هدفی نوشته‌ای: «${goal.title}». بعد از تست علاقه، با هم بررسی می‌کنیم که این هدف با علاقه‌هایت چقدر هم‌خوان است.`);
    return P;
  }
  const hol = holland.slice(0, 3).map(c => HOL[c] || c);
  push('intro', `تا اینجا ${testsDone > 1 ? `چند تست را انجام داده‌ای و` : 'تست علاقه را انجام داده‌ای و'} تصویر اولیه‌ای از تو دارم: علاقه‌هایت بیشتر به سمت ${list(hol)} است. یعنی احتمالاً در کارها و محیط‌هایی که این ویژگی‌ها را می‌خواهند، انرژی بیشتری می‌گیری و کمتر خسته می‌شوی.`);

  if (abilities?.length) {
    const strong = abilities.filter(a => a.topTitle).slice(0, 3).map(a => `«${a.topTitle}» (در «${a.title}»)`);
    if (strong.length) push('abilities', `از تست‌های دیگرت هم چند نقطه‌ی روشن دیده می‌شود: ${list(strong)}. این‌ها را کنار علاقه‌هایت بگذار؛ بهترین انتخاب‌ها معمولاً جایی‌اند که «دوست داشتن» و «توانستن» به هم می‌رسند.`);
  } else push('abilities', 'برای کامل‌تر شدن تصویر، پیشنهاد می‌کنم یکی دو تست توانایی و ارزش‌های کاری را هم انجام بدهی؛ تا الان فقط علاقه‌هایت را می‌دانیم و توانایی و ارزش‌هایت هنوز کنار گذاشته شده‌اند.');

  if (goal?.title) push('goal', `هدفی که برای خودت نوشته‌ای «${goal.title}» است. ${chosenMajor || chosenJob ? '' : 'اگر هنوز مطمئن نیستی چطور به آن برسی، نگران نباش؛ رشته و شغل زیر می‌توانند پلی بین علاقه‌ات و این هدف باشند.'}`);

  if (chosenMajor || chosenJob) {
    const bits = [chosenMajor ? `رشته‌ی «${chosenMajor.name}»` : null, chosenJob ? `شغل «${chosenJob.name}»` : null].filter(Boolean);
    push('choice', `تو تا الان ${list(bits)} را انتخاب کرده‌ای و این را در مسیرت می‌بینی. هر وقت دلت خواست می‌توانی عوضش کنی؛ تغییر نظر در این مرحله نشانه‌ی ضعف نیست، نشانه‌ی شناخت بیشتر است.`);
  } else if (majors?.length) {
    push('choice', `بر اساس علاقه‌هایت، رشته‌هایی مثل ${list(names(majors, 3))}${jobs?.length ? ` و شغل‌هایی مثل ${list(names(jobs, 3))}` : ''} بیشترین همپوشانی را دارند. هنوز هیچ‌کدام را انتخاب نکرده‌ای، که کاملاً اشکالی ندارد؛ فقط پیشنهاد می‌کنم صفحه‌ی دو سه تایش را بخوانی و ببینی کدام حس بهتری می‌دهد.`);
  }

  // قدم‌های بعدی بر اساس وضعیت
  const next = [];
  if (!goal) next.push('یک هدف کوچک و مشخص برای خودت بنویسی (در بخش «کوچ من»)');
  if (!chosenMajor && majors?.length) next.push('از بین رشته‌های پیشنهادی، یکی دو مورد را با دقت بخوانی');
  if (!planStarted) next.push('یک برنامه‌ی مطالعه یا کنکور بسازی تا مسیر به اقدام روزانه تبدیل شود');
  if (!coaching) next.push('اگر دوست داشتی، با یک کوچ یا مشاور واقعی هم صحبت کنی');
  if (/دوازدهم|فارغ|کنکور/.test(grade || '')) next.push('زمان انتخاب رشته‌ی کنکور که رسید، از بخش «انتخاب رشته‌ی کنکور» برای چیدن لیست نهایی کمک بگیری');
  if (next.length) push('next', `برای قدم بعد، اگر بخواهم کنارت باشم این‌ها را پیشنهاد می‌کنم: ${list(next)}. لازم نیست همه را همین امروز انجام بدهی؛ یک قدم کوچک کافی است.`);
  else push('next', 'مسیرت از نظر ساختار کامل است و مهم‌ترین قدم‌ها را برداشته‌ای 👏 حالا مهم‌ترین کار ادامه دادن است: هر هفته اقدام‌هایت را مرور کن و اگر چیزی عوض شد، مسیر را به‌روز کن.');

  push('closing', 'یادت باشد این مسیر زنده است؛ با هر تست تازه یا تغییر نظر، دقیق‌تر می‌شود. اگر جایی گیر کردی، مشاور هوش مصنوعی یا یک متخصص واقعی کنارت هستند.');
  return P;
}

// مقدمه‌ی دوستانه برای نتیجه‌ی تحلیل انتخاب رشته‌ی کنکور
export function konkurNarrative({ mode, group, rank, tiers, warnings, interestsCount }) {
  const P = []; const push = (kind, text) => { if (clean(text)) P.push({ kind, text: clean(text) }); };
  const total = tiers.ambitious.length + tiers.realistic.length + tiers.safe.length;
  if (mode === 'guide_only') {
    push('intro', 'فعلاً فهرست رشته‌محل‌های این گروه آزمایشی در سایت بارگذاری نشده، برای همین نمی‌توانم شانس قبولی را برایت تخمین بزنم. اما چیزی که می‌توانم بگویم همان بخش مهم‌تر است: اول علاقه‌هایت را مرتب کن، بعد با دفترچه‌ی رسمی سازمان سنجش، کدرشته‌محل‌ها را پیدا کن و با روش سه‌دسته‌ای (خوش‌بینانه، منطقی، مطمئن) بچین. راهنمای گام‌به‌گام همین صفحه دقیقاً همین را نشان می‌دهد.');
    return P;
  }
  push('intro', `با رتبه‌ی ${rank.toLocaleString('en-US')} در سهمیه‌ات برای گروه «${group}»، ${total} رشته‌محل را بررسی کردم و در سه دسته چیدم. یادت باشد این یک تخمین بر پایه‌ی داده‌ی سال‌های قبل است، نه پیش‌بینی قطعی؛ رتبه‌ی قبولی هر سال کمی بالا و پایین می‌شود.`);
  if (tiers.safe.length < Math.max(3, Math.round(total * 0.2))) push('warn', 'نکته‌ی مهم: تعداد انتخاب‌های مطمئن‌ات کم است. بهتر است ته لیستت چند گزینه‌ی کاملاً مطمئن بگذاری تا اگر اتفاق ناخواسته‌ای افتاد، بی‌دانشگاه نمانی.');
  if (interestsCount === 0) push('tip', 'چون هنوز رشته‌ی مورد علاقه‌ای مشخص نکرده بودی، ترتیب را فقط بر اساس نزدیکی رتبه‌ات (و شهر و نوع دوره‌ای که انتخاب کردی) چیدم. اگر علاقه‌هایت را مشخص کنی، چینش خیلی دقیق‌تر و شخصی‌تر می‌شود.');
  for (const w of warnings || []) push('warn', w);
  push('closing', 'پیشنهاد من این است که این لیست را یک «پیش‌نویس» بدانی: با خانواده یا مشاور حضوری مرورش کن، کدها را با دفترچه‌ی رسمی تطبیق بده، و ثبت نهایی را فقط از سامانه‌ی رسمی سازمان سنجش انجام بده.');
  return P;
}
